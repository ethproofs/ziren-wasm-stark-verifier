import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

import {
  main,
  verify_stark,
  verify_stark_with_public_inputs,
  verify_groth16,
  verify_plonk,
} from './pkg-node/ziren_wasm_stark_verifier.js';

// Convert a hexadecimal string (with or without 0x prefix) to a Uint8Array
const fromHexString = (hexString) =>
  Uint8Array.from(Buffer.from(hexString.replace(/^0x/, ''), 'hex'));

async function testVerification() {
  console.log('🧪 Testing Ziren WASM STARK Verifier\n');

  try {
    main();
    console.log('✅ WASM module initialized\n');

    // Load proof and verification key
    const proofPath = path.join(__dirname, 'binaries', 'zkm-eth-proof.bin');
    const vkPath = path.join(__dirname, 'binaries', 'zkm-vk.bin');

    console.log('\nLoading proof and verification key...');
    const proofBytes = fs.readFileSync(proofPath);
    const vkBytes = fs.readFileSync(vkPath);

    console.log(`  Proof size: ${proofBytes.length} bytes`);
    console.log(`  VK size: ${vkBytes.length} bytes`);

    // Test verification
    console.log('\n🔍 Verifying proof...');
    const start = performance.now();
    const result = verify_stark(proofBytes, vkBytes);
    const end = performance.now();
    console.log(`✅ Proof verification result: ${result}`);

    console.log('\n📊 Verification Summary:');
    console.log(`  STARK proof: ${result ? '✅ VALID' : '❌ INVALID'}`);
    console.log(`  Time taken: ${end - start} milliseconds`);
    if (!result) process.exitCode = 1;

    // Verify the fibonacci fixtures generated by `example/host`
    console.log('\n🔍 Verifying example fixtures...');
    const jsonDir = path.join(__dirname, 'example', 'json');
    for (const file of fs.readdirSync(jsonDir)) {
      const fixture = JSON.parse(fs.readFileSync(path.join(jsonDir, file), 'utf8'));
      const proof = fromHexString(fixture.proof);
      const publicInputs = fromHexString(fixture.public_inputs);

      let valid;
      if (fixture.mode === 'stark') {
        valid = verify_stark_with_public_inputs(proof, publicInputs, fromHexString(fixture.vkey));
      } else if (fixture.mode === 'groth16') {
        valid = verify_groth16(proof, publicInputs, fixture.vkey_hash);
      } else if (fixture.mode === 'plonk') {
        valid = verify_plonk(proof, publicInputs, fixture.vkey_hash);
      } else {
        throw new Error(`Unknown proof mode "${fixture.mode}" in ${file}`);
      }

      console.log(`  ${fixture.mode} (${file}): ${valid ? '✅ VALID' : '❌ INVALID'}`);
      if (!valid) process.exitCode = 1;
    }
  } catch (error) {
    console.error('❌ Error during verification:', error.message);
    console.error('Stack trace:', error.stack);
    process.exit(1);
  }
}

testVerification();
